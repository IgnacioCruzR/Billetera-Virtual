import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const settings = (page: Page) => page.getByRole('main', { name: 'Configuración' })
const tabs = (page: Page) => page.getByRole('navigation', { name: 'Secciones de configuración' })
const navigate = (page: Page, name: string) => page.getByRole('navigation', { name: 'Navegación principal' }).getByRole('button', { name, exact: true }).click()
const section = (page: Page, name: string) => tabs(page).getByRole('button', { name, exact: true }).click()

test.beforeEach(async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-11-24T12:00:00Z'))
})

