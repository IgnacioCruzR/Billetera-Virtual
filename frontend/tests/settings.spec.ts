async function createCategory(page: Page, name: string) {
  await settings(page).getByRole('button', { name: 'Nueva categoría' }).click()
  const dialog = page.getByRole('dialog', { name: 'Nueva categoría' })
  await dialog.getByLabel('Nombre de la categoría').fill(name)
  await dialog.getByRole('button', { name: 'Guardar categoría' }).click()
  await expect(dialog).toBeHidden()
}
async function categoryAction(page: Page, name: string, action: string) {
  await page.getByRole('button', { name: 'Acciones de ' + name, exact: true }).click()
  await page.getByRole('button', { name: action, exact: true }).click()
}

test('comparte categorías activas, conserva el historial y bloquea borrar una categoría en uso', async ({ page }) => {
  await page.goto('/#configuracion?seccion=categorias')
  await createCategory(page, 'Educación familiar')
  await page.getByRole('button', { name: 'Registrar movimiento', exact: true }).click()
  const record = page.getByRole('dialog', { name: 'Registrar movimiento' })
  await record.getByLabel('Monto (CLP)').fill('4500')
  await record.getByLabel('Categoría').selectOption({ label: 'Educación familiar' })
  await record.getByLabel('Descripción (opcional)').fill('Taller de categoría')
  await record.getByRole('button', { name: 'Guardar movimiento' }).click()
  await expect(record).toBeHidden()
  await categoryAction(page, 'Educación familiar', 'Archivar')
  let dialog = page.getByRole('dialog', { name: 'Archivar categoría' })
  await dialog.getByRole('button', { name: 'Archivar categoría' }).click()
  await expect(dialog).toBeHidden()
  await categoryAction(page, 'Educación familiar', 'Consultar eliminación')
  dialog = page.getByRole('dialog', { name: 'Eliminar categoría' })
  await expect(dialog).toContainText('La categoría tiene referencias financieras')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Registrar movimiento', exact: true }).click()
  await expect(record.getByRole('option', { name: 'Educación familiar' })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await navigate(page, 'Movimientos')
  await expect(page.getByRole('table', { name: 'Historial de movimientos' })).toContainText('Educación familiar')
  await navigate(page, 'Configuración')
  await section(page, 'Categorías')
  await categoryAction(page, 'Educación familiar', 'Reactivar')
  dialog = page.getByRole('dialog', { name: 'Reactivar categoría' })
  await dialog.getByRole('button', { name: 'Reactivar categoría' }).click()
  await expect(dialog).toBeHidden()
  await createCategory(page, 'Sin referencias')
  await categoryAction(page, 'Sin referencias', 'Eliminar')
  dialog = page.getByRole('dialog', { name: 'Eliminar categoría' })
  await dialog.getByRole('button', { name: 'Eliminar categoría' }).click()
  await expect(page.getByRole('button', { name: 'Acciones de Sin referencias' })).toHaveCount(0)
})

test('aplica reglas de avisos, privacidad global y descarga validada en móvil', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 760 })
  await page.goto('/#configuracion?seccion=notificaciones')
  const select = settings(page).getByLabel('Sección de configuración')
  await settings(page).getByLabel('Anticipación de cobros y pagos').selectOption('7')
  await settings(page).getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(settings(page).getByText('Guardado correctamente')).toBeVisible()
  const alerts = page.getByRole('button', { name: /^Notificaciones/ })
  await alerts.click()
  await expect(page.getByText('Internet hogar', { exact: false })).toBeVisible()
  await page.keyboard.press('Escape')
  await settings(page).getByLabel('Mostrar notificaciones en la aplicación').uncheck()
  await settings(page).getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(settings(page).getByText('Guardado correctamente')).toBeVisible()
  await alerts.click()
  await expect(page.getByText('No tienes avisos pendientes.')).toBeVisible()
  await page.keyboard.press('Escape')
  await select.selectOption('privacidad')
  await settings(page).getByRole('button', { name: 'Ocultar montos', exact: true }).click()
  await page.getByRole('button', { name: 'Abrir menú' }).click()
  await navigate(page, 'Dashboard')
  await expect(page.getByRole('button', { name: 'Mostrar montos', exact: true })).toBeVisible()
  await expect(page.getByRole('main')).not.toContainText(/\$-?\d/)
  await page.getByRole('button', { name: 'Abrir menú' }).click()
  await navigate(page, 'Configuración')
  await select.selectOption('datos')
  await settings(page).getByLabel('Conjunto de datos').selectOption('categories')
  await settings(page).getByRole('button', { name: 'Preparar exportación' }).click()
  await expect(settings(page).getByRole('region', { name: 'Vista previa de exportación' })).toContainText('9 registros')
  const download = page.waitForEvent('download')
  await settings(page).getByRole('button', { name: 'Descargar CSV de demostración' }).click()
  const exportFile = await download
  expect(exportFile.suggestedFilename()).toBe('billetera-demo-categories-2026-11-24.csv')
  expect(await readFile((await exportFile.path())!, 'utf8')).toContain('Alimentación')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
})

test('revoca IA, limpia informes y reinicia los datos al cerrar la sesión', async ({ page }) => {
  await page.goto('/#configuracion?seccion=asistente')
  await settings(page).getByRole('button', { name: 'Autorizar en esta sesión' }).click()
  await navigate(page, 'Asistente IA')
  await page.getByRole('button', { name: 'Configurar Situación financiera' }).click()
  await page.getByRole('button', { name: 'Revisar solicitud' }).click()
  await page.getByRole('button', { name: 'Generar análisis' }).click()
  const history = page.getByRole('region', { name: 'Informes de esta sesión' })
  await expect(history).toContainText('Situación financiera')
  await navigate(page, 'Configuración')
  await section(page, 'Asistente IA')
  await settings(page).getByRole('button', { name: 'Revocar autorización' }).click()
  await page.getByRole('button', { name: 'Confirmar revocación' }).click()
  await navigate(page, 'Asistente IA')
  await expect(page.getByRole('button', { name: 'Configurar Situación financiera' })).toBeDisabled()
  await expect(history).toContainText('Situación financiera')
  await navigate(page, 'Configuración')
  await section(page, 'Asistente IA')
  await settings(page).getByRole('button', { name: 'Eliminar informes de la sesión' }).click()
  await page.getByRole('button', { name: 'Confirmar eliminación' }).click()
  await expect(settings(page).getByRole('button', { name: 'Eliminar informes de la sesión' })).toBeDisabled()
  await section(page, 'Categorías')
  await createCategory(page, 'Temporal de la sesión')
  await section(page, 'Seguridad')
  await settings(page).getByRole('button', { name: 'Cerrar sesión' }).click()
  await page.getByRole('button', { name: 'Confirmar cierre de sesión' }).click()
  await expect(page.getByRole('heading', { name: 'Inicio de sesión', exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Entrar a la demostración' }).click()
  await navigate(page, 'Configuración')
  await section(page, 'Categorías')
  await expect(page.getByRole('button', { name: 'Acciones de Temporal de la sesión' })).toHaveCount(0)
  await section(page, 'Asistente IA')
  await expect(settings(page)).toContainText('Sin decisión registrada')
})

test('conserva un borrador si falla el guardado y el formulario de contraseña solo comprueba valores de ensayo', async ({ page }) => {
  await page.addInitScript('globalThis.__failSettings = true')
  await page.route('**/src/features/settings/settings-data.ts*', async route => {
    const response = await route.fetch()
    const source = await response.text()
    await route.fulfill({ response, body: source.replace('async updateProfile(name) {', 'async updateProfile(name) { if (globalThis.__failSettings) throw new Error("No se pudo guardar el perfil.");') })
  })
  await page.goto('/#configuracion')
  await settings(page).getByLabel('Nombre visible').fill('Paz Mora')
  await settings(page).getByRole('button', { name: 'Guardar perfil' }).click()
  await expect(settings(page).getByRole('alert')).toContainText('No se pudo guardar el perfil.')
  await expect(settings(page).getByLabel('Nombre visible')).toHaveValue('Paz Mora')
  await page.evaluate('globalThis.__failSettings = false')
  await settings(page).getByRole('button', { name: 'Guardar perfil' }).click()
  await expect(page.getByRole('button', { name: 'Preferencias de Paz Mora' })).toBeVisible()
  await section(page, 'Seguridad')
  await settings(page).getByLabel('Contraseña actual de ejemplo').fill('Ficticia-anterior!')
  await settings(page).getByLabel('Nueva contraseña de ejemplo').fill('Ficticia-nueva123!')
  await settings(page).getByLabel('Confirma la nueva contraseña').fill('Distinta')
  await settings(page).getByRole('button', { name: 'Comprobar formulario' }).click()
  await expect(settings(page).getByRole('alert')).toContainText('deben coincidir')
  await settings(page).getByLabel('Confirma la nueva contraseña').fill('Ficticia-nueva123!')
  await settings(page).getByRole('button', { name: 'Comprobar formulario' }).click()
  await expect(settings(page).getByRole('alert')).toContainText('integrar la cuenta real')
  await expect(settings(page).getByLabel('Nueva contraseña de ejemplo')).toHaveValue('')
})
