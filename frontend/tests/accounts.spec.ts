import { expect, test, type Page } from '@playwright/test'

const account = (page: Page, name: string) => page.getByRole('article', { name, exact: true })
const summary = (page: Page) => page.getByRole('region', { name: 'Resumen de cuentas' })

async function action(page: Page, name: string, label: string) {
  await account(page, name).getByRole('button', { name: `Acciones de ${name}` }).click()
  await page.getByRole('dialog', { name: 'Acciones de la cuenta' }).getByRole('button', { name: label, exact: true }).click()
}

async function create(page: Page, name: string, amount: string) {
  await page.getByRole('button', { name: 'Nueva cuenta' }).click()
  const dialog = page.getByRole('dialog', { name: 'Nueva cuenta' })
  await dialog.getByLabel('Nombre de la cuenta').fill(name)
  await dialog.getByLabel('Saldo inicial (CLP)').fill(amount)
  await dialog.getByRole('button', { name: 'Crear cuenta' }).click()
  await expect(account(page, name)).toBeVisible()
}

test('crea y personaliza una cuenta, comparte el saldo y filtra su historial', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Mis cuentas' }).click()
  await expect(page.getByRole('button', { name: 'Mis cuentas' })).toHaveAttribute('aria-current', 'page')
  await expect(summary(page)).toContainText('$2.485.600')
  await expect(summary(page)).toContainText('$300.000')
  await expect(summary(page)).toContainText('$2.185.600')

  await page.getByRole('button', { name: 'Nueva cuenta' }).click()
  let dialog = page.getByRole('dialog', { name: 'Nueva cuenta' })
  await dialog.getByRole('button', { name: 'Crear cuenta' }).click()
  await expect(dialog.getByLabel('Nombre de la cuenta')).toHaveAttribute('aria-invalid', 'true')
  await dialog.getByLabel('Nombre de la cuenta').fill('Efectivo diario')
  await dialog.getByLabel('Tipo de cuenta').selectOption('efectivo')
  await dialog.getByLabel('Color personalizado').fill('#818cf8')
  await dialog.getByRole('button', { name: 'Icono Otra cuenta' }).click()
  await dialog.getByLabel('Saldo inicial (CLP)').fill('50.5')
  await dialog.getByRole('button', { name: 'Crear cuenta' }).click()
  await expect(dialog.getByLabel('Saldo inicial (CLP)')).toHaveAttribute('aria-invalid', 'true')
  await dialog.getByLabel('Saldo inicial (CLP)').fill('50000')
  await expect(dialog).toContainText('$50.000')
  await dialog.getByRole('button', { name: 'Crear cuenta' }).click()
  await expect(page.getByText('Cuenta creada.', { exact: true })).toBeVisible()
  await expect(account(page, 'Efectivo diario')).toContainText('$50.000')

  await page.getByRole('button', { name: 'Dashboard', exact: true }).click()
  const dashboardTotals = page.getByRole('region', { name: 'Saldos del dashboard' })
  await expect(dashboardTotals).toContainText('$2.535.600')
  await expect(dashboardTotals).toContainText('$1.850.000')
  await page.getByRole('button', { name: 'Mis cuentas' }).click()

  await action(page, 'Efectivo diario', 'Registrar ingreso')
  dialog = page.getByRole('dialog', { name: 'Registrar movimiento' })
  await expect(dialog.getByLabel('Cuenta de destino').locator('option:checked')).toHaveText('Efectivo diario')
  await dialog.getByLabel('Monto (CLP)').fill('20000')
  await dialog.getByLabel('Categoría').selectOption('otros-ingresos')
  await dialog.getByLabel(/Descripción/).fill('Ingreso de caja')
  await dialog.getByRole('button', { name: 'Guardar movimiento' }).click()
  await expect(account(page, 'Efectivo diario')).toContainText('$70.000')

  await action(page, 'Efectivo diario', 'Registrar gasto')
  dialog = page.getByRole('dialog', { name: 'Registrar movimiento' })
  await expect(dialog.getByLabel('Cuenta de origen').locator('option:checked')).toHaveText('Efectivo diario')
  await dialog.getByLabel('Monto (CLP)').fill('5000')
  await dialog.getByLabel('Categoría').selectOption('alimentacion')
  await dialog.getByLabel(/Descripción/).fill('Compra de caja')
  await dialog.getByRole('button', { name: 'Guardar movimiento' }).click()
  await expect(account(page, 'Efectivo diario')).toContainText('$65.000')

  await action(page, 'Efectivo diario', 'Editar cuenta')
  dialog = page.getByRole('dialog', { name: 'Editar cuenta' })
  await expect(dialog.getByLabel('Saldo inicial (CLP)')).toHaveCount(0)
  await dialog.getByLabel('Nombre de la cuenta').fill('Caja del mes')
  await dialog.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(account(page, 'Caja del mes')).toContainText('$65.000')
  await account(page, 'Caja del mes').getByRole('button', { name: 'Caja del mes', exact: true }).click()
  const detail = page.getByRole('dialog', { name: 'Caja del mes' })
  await expect(detail).toContainText('$50.000')
  await detail.getByRole('combobox', { name: 'Período del detalle' }).selectOption('quarter')
  await expect(detail).toContainText('Ingreso de caja')
  await detail.getByRole('button', { name: 'Ver historial de la cuenta' }).click()
  await expect(page.getByRole('button', { name: 'Quitar filtro Caja del mes' })).toBeVisible()
  const table = page.getByRole('table', { name: 'Historial de movimientos filtrados' })
  await expect(table.getByRole('row')).toHaveCount(3)
  await page.getByRole('button', { name: 'Acciones de Compra de caja' }).click()
  await page.getByRole('button', { name: 'Eliminar', exact: true }).click()
  await page.getByRole('dialog', { name: 'Eliminar movimiento' }).getByRole('button', { name: 'Eliminar movimiento' }).click()
  await expect(page.getByText('Movimiento eliminado.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Mis cuentas' }).click()
  await expect(account(page, 'Caja del mes')).toContainText('$70.000')
})

test('protege fondos reservados, transfiere sin variar el total y registra un ajuste aparte', async ({ page }) => {
  await page.goto('/#cuentas')
  await action(page, 'Cuenta de ahorro', 'Transferir dinero')
  let dialog = page.getByRole('dialog', { name: 'Registrar movimiento' })
  await dialog.getByLabel('Cuenta de destino').selectOption('vista')
  await dialog.getByLabel('Monto (CLP)').fill('1')
  await dialog.getByRole('button', { name: 'Guardar movimiento' }).click()
  await expect(dialog.getByText(/fondos reservados requieren liberación/)).toBeVisible()
  await dialog.getByRole('button', { name: 'Cancelar' }).click()

  await action(page, 'Cuenta vista', 'Transferir dinero')
  dialog = page.getByRole('dialog', { name: 'Registrar movimiento' })
  await dialog.getByLabel('Cuenta de destino').selectOption('ahorro')
  await dialog.getByLabel('Monto (CLP)').fill('500000')
  await dialog.getByRole('button', { name: 'Guardar movimiento' }).click()
  await expect(dialog.getByText('Saldo disponible insuficiente en la cuenta de origen.')).toBeVisible()
  await dialog.getByLabel('Monto (CLP)').fill('40000')
  await dialog.getByRole('button', { name: 'Guardar movimiento' }).click()
  await expect(page.getByText('Transferencia registrada.', { exact: true })).toBeVisible()
  await expect(account(page, 'Cuenta vista')).toContainText('$420.000')
  await expect(account(page, 'Cuenta de ahorro')).toContainText('$340.000')
  await expect(summary(page)).toContainText('$2.485.600')

  await action(page, 'Cuenta vista', 'Ajustar saldo')
  dialog = page.getByRole('dialog', { name: 'Ajustar saldo' })
  await expect(dialog).toContainText('$420.000')
  await dialog.getByLabel('Nuevo saldo real (CLP)').fill('420700')
  await dialog.getByLabel('Motivo del ajuste').fill('Recuento de efectivo')
  await dialog.getByRole('button', { name: 'Registrar ajuste' }).click()
  await expect(dialog.getByText('Confirma que quieres registrar el ajuste.', { exact: true })).toBeVisible()
  await dialog.getByRole('checkbox', { name: /Confirmo/ }).check()
  await dialog.getByRole('button', { name: 'Registrar ajuste' }).click()
  await expect(page.getByText('Ajuste registrado.', { exact: true })).toBeVisible()
  await expect(account(page, 'Cuenta vista')).toContainText('$420.700')
  await expect(summary(page)).toContainText('$2.486.300')
  await action(page, 'Cuenta vista', 'Ver detalle')
  const detail = page.getByRole('dialog', { name: 'Cuenta vista' })
  await expect(detail.getByRole('region', { name: 'Ajustes de saldo' })).toContainText('Recuento de efectivo')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Dashboard', exact: true }).click()
  const totals = page.getByRole('region', { name: 'Saldos del dashboard' })
  await expect(totals).toContainText('$2.486.300')
  await expect(totals).toContainText('$1.850.000')
  await expect(totals).toContainText('$1.234.400')
  await expect(page.getByRole('region', { name: 'Gastos hormiga' })).toContainText('$42.500')
})

test('archiva con saldo y referencias, restaura los selectores y elimina solo cuentas elegibles', async ({ page }) => {
  await page.goto('/#cuentas')
  await action(page, 'Cuenta vista', 'Archivar cuenta')
  let dialog = page.getByRole('dialog', { name: 'Archivar cuenta' })
  await expect(dialog).toContainText('Compromisos asociados: 2')
  await dialog.getByRole('button', { name: 'Archivar cuenta' }).click()
  await expect(page.getByText('Cuenta archivada.', { exact: true })).toBeVisible()
  await expect(summary(page)).toContainText('$2.485.600')
  await expect(summary(page)).toContainText('$2.025.600')
  await expect(account(page, 'Cuenta vista')).toHaveCount(0)

  await page.getByRole('button', { name: 'Registrar movimiento', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Registrar movimiento' })
  await expect(dialog.getByLabel('Cuenta de origen').locator('option[value="vista"]')).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Cancelar' }).click()

  await page.getByRole('button', { name: 'Archivadas (1)', exact: true }).click()
  await expect(account(page, 'Cuenta vista')).toContainText('$460.000')
  await action(page, 'Cuenta vista', 'Eliminar cuenta')
  dialog = page.getByRole('dialog', { name: 'Eliminar cuenta' })
  await expect(dialog).toContainText('Tiene compromisos asociados')
  await expect(dialog).toContainText('historial')
  await dialog.getByRole('button', { name: 'Entendido' }).click()

  await action(page, 'Cuenta vista', 'Reactivar cuenta')
  await page.getByRole('dialog', { name: 'Reactivar cuenta' }).getByRole('button', { name: 'Reactivar cuenta' }).click()
  await expect(page.getByText('Cuenta reactivada.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Activas (3)', exact: true }).click()
  await expect(account(page, 'Cuenta vista')).toContainText('$460.000')

  await create(page, 'Cuenta sin uso', '0')
  await action(page, 'Cuenta sin uso', 'Eliminar cuenta')
  await page.getByRole('dialog', { name: 'Eliminar cuenta' }).getByRole('button', { name: 'Eliminar cuenta' }).click()
  await expect(page.getByText('Cuenta eliminada.', { exact: true })).toBeVisible()
  await expect(account(page, 'Cuenta sin uso')).toHaveCount(0)
})

test.describe('móvil', () => {
  test.use({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })

  test('abre Mis cuentas y mantiene montos ocultos en tarjetas, gráficos y detalle', async ({ page }) => {
    await page.goto('/')
    await page.getByRole('button', { name: 'Abrir menú' }).click()
    await page.getByRole('button', { name: 'Mis cuentas' }).click()
    await expect(page.getByRole('heading', { name: 'Mis cuentas', exact: true })).toBeVisible()
    await expect(summary(page)).toContainText('$2.485.600')
    await page.getByRole('button', { name: 'Ocultar montos' }).click()
    await expect(summary(page)).toContainText('$••••••')
    await expect(page.getByRole('region', { name: 'Distribución del dinero' })).not.toContainText('$2.485.600')
    await expect(page.getByRole('region', { name: 'Evolución del saldo' })).toContainText('$••••••')
    await expect(account(page, 'Cuenta corriente')).toContainText('$••••••')
    await account(page, 'Cuenta corriente').getByRole('button', { name: 'Cuenta corriente', exact: true }).click()
    const detail = page.getByRole('dialog', { name: 'Cuenta corriente' })
    await expect(detail).toContainText('$••••••')
    await page.keyboard.press('Escape')
    await page.setViewportSize({ width: 320, height: 720 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
  })
})
