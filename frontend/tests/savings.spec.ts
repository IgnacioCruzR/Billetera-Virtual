import { expect, test, type Page } from '@playwright/test'

const card = (page: Page, name: string) => page.getByRole('article', { name, exact: true })
const nav = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const overview = (page: Page) => page.getByRole('region', { name: 'Resumen de ahorro' })

async function goalAction(page: Page, goal: string, action: string) {
  await card(page, goal).getByRole('button', { name: `Acciones de ${goal}` }).click()
  await page.getByRole('dialog', { name: 'Acciones de la meta' }).getByRole('button', { name: action, exact: true }).click()
}

async function changeStatus(page: Page, goal: string, action: string) {
  await goalAction(page, goal, action)
  await page.getByRole('dialog', { name: action, exact: true }).getByRole('button', { name: action, exact: true }).click()
}

async function newGoal(page: Page, goal: string, amount: string, initial?: string) {
  await nav(page, 'Nueva meta').click()
  const form = page.getByRole('dialog', { name: 'Nueva meta' })
  await form.getByLabel('Plantilla visual').selectOption('tecnologia')
  await form.getByLabel('Nombre de la meta').fill(goal)
  await form.getByLabel('Monto objetivo (CLP)').fill(amount)
  if (initial) {
    await form.getByLabel('Aporte inicial (CLP)').fill(initial)
    await form.getByLabel('Cuenta del aporte inicial').selectOption('corriente')
  }
  await form.getByRole('button', { name: 'Crear meta' }).click()
  await expect(form).toBeHidden()
}

test.beforeEach(async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-11-24T12:00:00Z'))
})

test('crea una meta con aporte inicial, conserva fondos en pausa y los libera al cancelar', async ({ page }) => {
  await page.goto('/')
  await nav(page, 'Metas de ahorro').click()
  await expect(nav(page, 'Metas de ahorro')).toHaveAttribute('aria-current', 'page')
  await expect(card(page, 'Dinero reservado')).toContainText('$300.000')
  await newGoal(page, 'Equipo para trabajar', '100000', '30000')
  const goal = card(page, 'Equipo para trabajar')
  await expect(goal).toContainText('Tecnología')
  await expect(goal).toContainText('30 %')
  await expect(card(page, 'Dinero reservado')).toContainText('$330.000')
  await expect(overview(page)).toContainText('$2.485.600')
  await expect(overview(page)).toContainText('$2.155.600')
  await changeStatus(page, 'Equipo para trabajar', 'Pausar meta')
  await expect(goal).toContainText('Pausada')
  await expect(goal.getByRole('button', { name: 'Agregar aporte' })).toHaveCount(0)
  await expect(card(page, 'Objetivo de metas en progreso')).toContainText('$1.400.000')
  await expect(card(page, 'Dinero reservado')).toContainText('$330.000')
  await changeStatus(page, 'Equipo para trabajar', 'Reactivar meta')
  await expect(goal).toContainText('En progreso')

  await goalAction(page, 'Equipo para trabajar', 'Cancelar meta')
  const cancel = page.getByRole('dialog', { name: 'Cancelar meta' })
  await expect(cancel).toContainText('Se liberarán $30.000')
  await cancel.getByRole('button', { name: 'Cancelar meta' }).click()
  await expect(goal).toContainText('Cancelada')
  await expect(card(page, 'Dinero reservado')).toContainText('$300.000')
  await goal.getByRole('button', { name: 'Equipo para trabajar', exact: true }).click()
  const detail = page.getByRole('dialog', { name: 'Equipo para trabajar' })
  await expect(detail.getByRole('region', { name: 'Historial de reservas' })).toContainText('Liberación por cancelación')
  await detail.getByRole('link', { name: 'Cuenta corriente', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Cuenta corriente' })).toContainText('$1.725.600')
  await page.getByRole('dialog', { name: 'Cuenta corriente' }).getByRole('button', { name: 'Cerrar', exact: true }).click()
  await nav(page, 'Presupuestos').click()
  await expect(card(page, 'Alimentación')).toContainText('$314.400')
})

test('alcanza, libera parcialmente y finaliza con una compra que exige un registro independiente', async ({ page }) => {
  await page.goto('/#metas')
  await newGoal(page, 'Bicicleta', '20000')
  const goal = card(page, 'Bicicleta')
  async function contribute(amount: string) {
    await goal.getByRole('button', { name: 'Agregar aporte' }).click()
    const dialog = page.getByRole('dialog', { name: 'Agregar aporte' })
    await dialog.getByLabel('Cuenta del aporte').selectOption('vista')
    await dialog.getByLabel('Monto del aporte (CLP)').fill(amount)
    await expect(dialog.getByRole('definition').filter({ hasText: '100 %' })).toBeVisible()
    await dialog.getByRole('button', { name: 'Confirmar aporte' }).click()
    await expect(goal).toContainText('Alcanzada')
  }
  await contribute('20000')
  await nav(page, 'Dashboard').click()
  await expect(page.getByRole('region', { name: 'Resumen de metas de ahorro' })).toContainText('$320.000')
  await expect(page.getByRole('region', { name: 'Saldos del dashboard' })).toContainText('$2.485.600')
  await page.getByRole('button', { name: /^Notificaciones/ }).click()
  await expect(page.getByRole('dialog', { name: 'Bandeja de notificaciones' })).toContainText('Meta alcanzada')
  await page.keyboard.press('Escape')
  await nav(page, 'Metas de ahorro').click()
  await goalAction(page, 'Bicicleta', 'Liberar dinero reservado')
  const release = page.getByRole('dialog', { name: 'Liberar dinero reservado' })
  await release.getByLabel('Monto a liberar (CLP)').fill('5000')
  await release.getByRole('button', { name: 'Confirmar liberación' }).click()
  await expect(goal).toContainText('En progreso')
  await expect(goal).toContainText('75 %')
  await contribute('5000')
  await goalAction(page, 'Bicicleta', 'Finalizar meta')
  const finalize = page.getByRole('dialog', { name: 'Finalizar meta' })
  await finalize.getByRole('checkbox', { name: /registrar una compra/ }).check()
  await finalize.getByRole('button', { name: 'Finalizar meta' }).click()
  const movement = page.getByRole('dialog', { name: 'Registrar movimiento' })
  await expect(movement.getByLabel('Monto (CLP)')).toHaveValue('20000')
  await expect(movement.getByLabel('Cuenta de origen')).toHaveValue('vista')
  await movement.getByLabel('Categoría').selectOption('transporte')
  await movement.getByRole('button', { name: 'Guardar movimiento' }).click()
  await expect(goal).toContainText('Finalizada')
  await expect(card(page, 'Dinero reservado')).toContainText('$300.000')
  await nav(page, 'Movimientos').click()
  await page.getByRole('searchbox', { name: 'Buscar por descripción' }).fill('Bicicleta')
  await expect(page.getByRole('table', { name: 'Historial de movimientos filtrados' }).getByRole('row').filter({ hasText: 'Bicicleta' })).toHaveCount(1)
  await nav(page, 'Presupuestos').click()
  await expect(card(page, 'Transporte')).toContainText('$167.000')
})

test('impide aportar, gastar y archivar con fondos reservados y permite gastar después de liberar', async ({ page }) => {
  await page.goto('/#metas')
  const goal = card(page, 'Fondo de emergencia')
  await goal.getByRole('button', { name: 'Agregar aporte' }).click()
  const form = page.getByRole('dialog', { name: 'Agregar aporte' })
  await form.getByLabel('Cuenta del aporte').selectOption('ahorro')
  await form.getByLabel('Monto del aporte (CLP)').fill('1000')
  await form.getByRole('button', { name: 'Confirmar aporte' }).click()
  await expect(form).toContainText('La cuenta no tiene dinero libre suficiente')
  await form.getByRole('button', { name: 'Volver' }).click()
  await nav(page, 'Mis cuentas').click()
  const savingAccount = card(page, 'Cuenta de ahorro')
  await expect(savingAccount).toContainText('Reservado $300.000 · Libre $0')
  await savingAccount.getByRole('button', { name: 'Acciones de Cuenta de ahorro' }).click()
  await nav(page, 'Archivar cuenta').click()
  const archive = page.getByRole('dialog', { name: 'Archivar cuenta' })
  await expect(archive).toContainText('Libera las reservas de esta cuenta antes de archivarla.')
  await archive.getByRole('button', { name: 'Entendido' }).click()

  async function preparePurchase() {
    await nav(page, 'Registrar movimiento').click()
    const movement = page.getByRole('dialog', { name: 'Registrar movimiento' })
    await movement.getByLabel('Cuenta de origen').selectOption('ahorro')
    await movement.getByLabel('Categoría').selectOption('salud')
    await movement.getByLabel('Monto (CLP)').fill('5000')
    await movement.getByLabel(/Descripción/).fill('Compra financiada por reserva')
    await movement.getByRole('button', { name: 'Guardar movimiento' }).click()
    return movement
  }
  const blocked = await preparePurchase()
  await expect(blocked).toContainText('Libera fondos de tus metas antes de usar el dinero reservado.')
  await blocked.getByRole('link', { name: 'Revisar reservas de la cuenta' }).click()
  await goalAction(page, 'Fondo de emergencia', 'Liberar dinero reservado')
  const release = page.getByRole('dialog', { name: 'Liberar dinero reservado' })
  await expect(release.getByLabel('Cuenta con reserva')).toHaveValue('ahorro')
  await release.getByLabel('Monto a liberar (CLP)').fill('5000')
  await release.getByRole('button', { name: 'Confirmar liberación' }).click()
  await expect(card(page, 'Dinero reservado')).toContainText('$295.000')
  await expect(overview(page)).toContainText('$2.485.600')
  await expect(await preparePurchase()).toBeHidden()
  await expect(overview(page)).toContainText('$2.480.600')
})

test('lleva un escenario de Gastos hormiga al planificador móvil y conserva la privacidad', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 860 })
  await page.goto('/#hormiga')
  await nav(page, 'Simular ahorro').click()
  const simulation = page.getByRole('region', { name: 'Simulador de ahorro' })
  await simulation.getByRole('checkbox', { name: 'Incluir gastos marcados como prescindibles' }).check()
  await simulation.getByRole('button', { name: 'Comparar este escenario en Metas de ahorro' }).click()
  const planner = page.getByRole('region', { name: 'Planificador de ahorro' })
  await expect(planner.getByLabel('Meta del escenario')).toHaveValue('emergency')
  await expect(planner).toContainText('$672')
  await planner.getByLabel('Aporte mensual habitual (CLP)').fill('6000')
  await expect(planner).toContainText('Este escenario podría adelantar la meta 12 meses.')
  await planner.getByLabel('Fecha deseada').fill('2026-11-30')
  await expect(planner).toContainText('Sin plazo aplicable')
  await expect(card(page, 'Dinero reservado')).toContainText('$300.000')
  await nav(page, 'Ocultar montos').click()
  await expect(planner).not.toContainText('$672')
  await expect(card(page, 'Dinero reservado')).toContainText('$••••••')
  await nav(page, 'Nueva meta').click()
  const form = page.getByRole('dialog', { name: 'Nueva meta' })
  await expect(form).toBeVisible()
  expect(await form.evaluate(node => Math.round(node.getBoundingClientRect().bottom))).toBe(860)
  await form.getByRole('button', { name: 'Volver' }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
})
