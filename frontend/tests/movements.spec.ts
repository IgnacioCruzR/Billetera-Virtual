  await page.getByRole('button', { name: 'Filtros avanzados' }).click()
  await page.getByLabel('Monto mínimo').fill('100000')
  await page.getByLabel('Monto máximo').fill('130000')
  await expect(table(page).getByRole('row')).toHaveCount(2)
