import { readFile } from 'node:fs/promises'
import { expect, test, type Page } from '@playwright/test'

const summary = (page: Page) => page.getByRole('region', { name: 'Resumen del período' })
const table = (page: Page) => page.getByRole('table', { name: 'Historial de movimientos filtrados' })
const search = (page: Page) => page.getByRole('searchbox', { name: 'Buscar por descripción' })

async function newMovement(page: Page) {
  await page.getByRole('button', { name: 'Nuevo movimiento', exact: true }).click()
  return page.getByRole('dialog', { name: 'Registrar movimiento' })
}

async function rowAction(page: Page, description: string, action: string) {
  await page.getByRole('button', { name: `Acciones de ${description}` }).click()
  await page.getByRole('button', { name: action, exact: true }).click()
}

