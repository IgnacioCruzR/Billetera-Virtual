test.describe('móvil', () => {
  test.use({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })

  test('abre el módulo y usa el drawer de filtros y las acciones de las tarjetas', async ({ page }) => {
    await page.goto('/')
    await page.getByRole('button', { name: 'Abrir menú' }).click()
    await page.getByRole('button', { name: 'Movimientos', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Movimientos', exact: true })).toBeVisible()
    await expect(table(page)).toBeHidden()
    await page.getByRole('button', { name: 'Filtros', exact: true }).click()
    const drawer = page.getByRole('dialog', { name: 'Filtros del historial' })
    await drawer.getByLabel('Clasificación', { exact: true }).selectOption('necesario')
    await drawer.getByRole('button', { name: 'Ver resultados' }).click()
    const cards = page.getByRole('list', { name: 'Movimientos del historial' })
    await expect(cards.getByRole('listitem')).toHaveCount(1)
    await expect(cards).toContainText('Medicamento de uso diario')
    await rowAction(page, 'Medicamento de uso diario', 'Ver detalle')
    await expect(page.getByRole('dialog', { name: 'Detalle del movimiento' })).toContainText('Gasto pequeño necesario')
    await page.keyboard.press('Escape')
    await page.setViewportSize({ width: 320, height: 720 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
    await expect(page.getByRole('button', { name: 'Nuevo movimiento' })).toBeVisible()
  })
})
