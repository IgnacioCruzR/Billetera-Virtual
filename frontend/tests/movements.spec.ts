  await expect(page.getByRole('article', { name: 'Cuenta de ahorro' })).toContainText('$340.000')
  await page.getByRole('button', { name: 'Dashboard', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Saldos del dashboard' })).toContainText('$2.508.100')
  await expect(page.getByRole('region', { name: 'Gastos hormiga' })).toContainText('$42.500')
  await page.goBack()
