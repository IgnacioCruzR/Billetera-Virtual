import { expect, test, type Page } from '@playwright/test'

const card = (page: Page, name: string) => page.getByRole('article', { name, exact: true })
const history = (page: Page) => page.getByRole('region', { name: 'Historial de gastos', exact: true })

test.beforeEach(async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-11-24T12:00:00Z'))
})

test('clasifica en lote, conserva marcas al cambiar la detección y enlaza con el movimiento original', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Gastos hormiga', exact: true }).click()
  await expect(card(page, 'Gasto acumulado')).toContainText('$45.200')
  await expect(card(page, 'Proyección anual')).toContainText('$678.000')
  await page.getByRole('region', { name: 'Patrones de consumo' }).getByRole('button', { name: 'Café de la mañana' }).click()
  const report = history(page)
  await expect(report.getByText('4 resultados · 0 seleccionados')).toBeVisible()
  await report.getByRole('checkbox', { name: /Seleccionar Café de la mañana del/ }).nth(0).check()
  await report.getByRole('checkbox', { name: /Seleccionar Café de la mañana del/ }).nth(1).check()
  await report.getByRole('button', { name: 'Clasificar selección' }).click()
  const review = page.getByRole('dialog', { name: 'Confirmar clasificación múltiple' })
  await expect(review).toContainText('Se actualizarán 2 movimientos.')
  await review.getByRole('button', { name: 'Volver' }).click()
  await expect(report.getByRole('cell', { name: 'Gasto pequeño prescindible', exact: true })).toHaveCount(0)
  await report.getByRole('button', { name: 'Clasificar selección' }).click()
  await review.getByLabel('Nueva clasificación').selectOption('prescindible')
  await review.getByRole('button', { name: 'Aplicar clasificación' }).click()
  await expect(page.getByText('Clasificaciones actualizadas.', { exact: true })).toBeVisible()
  await expect(report.getByRole('cell', { name: 'Gasto pequeño prescindible', exact: true })).toHaveCount(2)

  await page.getByRole('button', { name: 'Configurar detección' }).click()
  const settings = page.getByRole('dialog', { name: 'Configurar detección' })
  await expect(settings.getByLabel('Monto máximo (CLP)')).toHaveValue('5000')
  await settings.getByLabel('Monto máximo (CLP)').fill('0')
  await settings.getByRole('button', { name: 'Guardar criterio' }).click()
  await expect(settings.getByLabel('Monto máximo (CLP)')).toHaveAttribute('aria-invalid', 'true')
  await settings.getByLabel('Monto máximo (CLP)').fill('1000')
  await settings.getByRole('checkbox', { name: 'Alimentación' }).check()
  await settings.getByRole('button', { name: 'Guardar criterio' }).click()
  await expect(report.getByRole('cell', { name: 'Gasto pequeño prescindible', exact: true })).toHaveCount(2)
  await report.getByRole('button', { name: 'Café de la mañana', exact: true }).first().click()
  await expect(page.getByRole('dialog', { name: 'Detalle del movimiento' })).toContainText('Gasto pequeño prescindible')
  await page.getByRole('dialog', { name: 'Detalle del movimiento' }).getByRole('button', { name: 'Cerrar' }).click()
  await page.getByRole('button', { name: 'Dashboard', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Saldos del dashboard' })).toContainText('$2.485.600')
  await expect(page.getByRole('region', { name: 'Gastos hormiga', exact: true })).toContainText('0 por revisar')
  await page.getByRole('button', { name: 'Presupuestos', exact: true }).click()
  await expect(card(page, 'Alimentación')).toContainText('$314.400')
  await card(page, 'Alimentación').getByRole('button', { name: 'Alimentación', exact: true }).click()
  await page.getByRole('link', { name: 'Ver análisis de la categoría' }).click()
  await expect(history(page).getByLabel('Categoría de gasto')).toHaveValue('alimentacion')
  await expect(history(page).getByRole('checkbox', { name: 'Solo gastos incluidos en el análisis' })).toBeChecked()
})

test('excluye y restablece un gasto sin alterar su registro financiero', async ({ page }) => {
  await page.goto('/#hormiga')
  const report = history(page)
  await report.getByRole('searchbox', { name: 'Buscar gastos' }).fill('pelicula')
  await report.getByRole('button', { name: 'Acciones de Película en línea' }).click()
  await page.getByRole('button', { name: 'Excluir del análisis', exact: true }).click()
  await page.getByRole('dialog', { name: 'Confirmar clasificación' }).getByRole('button', { name: 'Aplicar clasificación' }).click()
  await expect(report.getByRole('cell', { name: 'Excluido del análisis' })).toBeVisible()
  await expect(card(page, 'Gastos prescindibles')).toContainText('$0')
  await report.getByRole('button', { name: 'Acciones de Película en línea' }).click()
  await page.getByRole('button', { name: 'Restablecer clasificación' }).click()
  await page.getByRole('dialog', { name: 'Confirmar clasificación' }).getByRole('button', { name: 'Aplicar clasificación' }).click()
  await expect(report.getByRole('cell', { name: 'Sin clasificación' })).toBeVisible()
  await expect(report).toContainText('$2.150')
  await page.getByRole('button', { name: 'Mis cuentas', exact: true }).click()
  await card(page, 'Cuenta vista').getByRole('button', { name: 'Cuenta vista', exact: true }).click()
  await page.getByRole('link', { name: 'Ver gastos hormiga de la cuenta' }).click()
  await expect(history(page).getByLabel('Cuenta de gasto')).toHaveValue('vista')
})

test('deduplica el simulador y protege importes en móvil', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 860 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Abrir menú' }).click()
  await page.getByRole('button', { name: 'Gastos hormiga', exact: true }).click()
  await page.getByRole('button', { name: 'Simular ahorro' }).click()
  const sim = page.getByRole('region', { name: 'Simulador de ahorro' })
  await sim.getByRole('checkbox', { name: 'Incluir gastos marcados como prescindibles' }).check()
  await sim.getByRole('checkbox', { name: /Película en línea/ }).check()
  await expect(sim.getByText('1 gasto seleccionado', { exact: true })).toBeVisible()
  await expect(sim).toContainText('$672')
  await sim.getByRole('slider', { name: 'Reducción de Película en línea' }).press('End')
  await expect(sim).toContainText('$2.688')
  await page.getByRole('button', { name: 'Ocultar montos' }).click()
  await expect(sim).not.toContainText('$2.688')
  await expect(card(page, 'Gasto acumulado')).toContainText('$••••••')
  await sim.getByRole('button', { name: 'Restablecer simulación' }).click()
  await expect(sim.getByText('0 gastos seleccionados', { exact: true })).toBeVisible()
  await sim.getByRole('button', { name: 'Cerrar simulador' }).click()
  await page.getByRole('button', { name: 'Configurar detección' }).click()
  const settings = page.getByRole('dialog', { name: 'Configurar detección' })
  expect(await settings.evaluate(dialog => Math.round(dialog.getBoundingClientRect().bottom))).toBe(860)
  await settings.getByRole('checkbox', { name: 'Detección automática' }).uncheck()
  await settings.getByRole('button', { name: 'Guardar criterio' }).click()
  await expect(page.getByText('Detección automática desactivada. Se conservan las marcas manuales.')).toBeVisible()
  await expect(history(page).getByRole('list', { name: 'Tarjetas de gastos identificados' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
})
