import { expect, test, type Page } from '@playwright/test'

const overview = (page: Page, title: string) => page.getByRole('article', { name: title, exact: true })
const history = (page: Page) => page.getByRole('region', { name: 'Historial de compromisos' })
const row = (page: Page, name: string) => history(page).getByRole('row').filter({ has: page.getByRole('button', { name, exact: true }) })

async function create(page: Page, draft: { name: string; amount: string; date: string; receipt?: boolean }) {
  await page.getByRole('button', { name: 'Nuevo compromiso', exact: true }).click()
  const form = page.getByRole('dialog', { name: 'Nuevo compromiso' })
  if (draft.receipt) await form.getByRole('button', { name: 'Cobro', exact: true }).click()
  await form.getByLabel(draft.receipt ? 'Nombre del cobro' : 'Nombre del pago').fill(draft.name)
  await form.getByLabel('Monto (CLP)').fill(draft.amount)
  await form.getByLabel(draft.receipt ? 'Cuenta de destino' : 'Cuenta de origen').selectOption('corriente')
  await form.getByLabel('Categoría').selectOption(draft.receipt ? 'freelance' : 'alimentacion')
  await form.getByLabel(draft.receipt ? 'Fecha prevista de recepción' : 'Fecha de vencimiento').fill(draft.date)
  await form.getByRole('button', { name: 'Crear compromiso' }).click()
  await expect(form).toBeHidden()
}

test.beforeEach(async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-11-24T12:00:00Z'))
})

test('confirma un pago vencido una sola vez y actualiza saldo, historial y presupuesto', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Cobros y pagos', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Cobros y pagos', exact: true })).toBeVisible()
  await create(page, { name: 'Compra feria', amount: '65000', date: '2026-11-20' })
  await expect(row(page, 'Compra feria')).toContainText('Vencido')
  await expect(overview(page, 'Saldo actual')).toContainText('$2.485.600')
  await expect(overview(page, 'Saldo proyectado')).toContainText('$2.730.600')
  await page.getByRole('button', { name: 'Presupuestos', exact: true }).click()
  await expect(overview(page, 'Alimentación')).toContainText('$314.400')
  await page.getByRole('button', { name: 'Cobros y pagos', exact: true }).click()
  await row(page, 'Compra feria').getByRole('button', { name: 'Compra feria', exact: true }).click()
  const detail = page.getByRole('dialog', { name: 'Compra feria' })
  await expect(detail).toContainText('4 días de atraso')
  await detail.getByRole('button', { name: 'Confirmar pago' }).click()
  const confirm = page.getByRole('dialog', { name: 'Confirmar pago' })
  await expect(confirm).toContainText('$65.000')
  await confirm.getByRole('button', { name: 'Confirmar pago' }).click()
  await expect(page.getByText('Pago confirmado.', { exact: true })).toBeVisible()
  await expect(row(page, 'Compra feria')).toContainText('Confirmado')
  await expect(overview(page, 'Saldo actual')).toContainText('$2.420.600')
  await expect(overview(page, 'Saldo proyectado')).toContainText('$2.730.600')

  await row(page, 'Compra feria').getByRole('button', { name: 'Compra feria', exact: true }).click()
  await expect(detail.getByRole('button', { name: 'Confirmar pago' })).toHaveCount(0)
  await detail.getByRole('button', { name: 'Ver movimiento asociado' }).click()
  const movement = page.getByRole('dialog', { name: 'Detalle del movimiento' })
  await expect(movement).toContainText('Compra feria')
  await expect(movement).toContainText('$65.000')
  await movement.getByRole('button', { name: 'Ver compromiso asociado' }).click()
  await expect(detail).toBeVisible()
  await detail.getByRole('button', { name: 'Cerrar', exact: true }).click()

  await page.getByRole('button', { name: 'Movimientos', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Buscar por descripción' }).fill('Compra feria')
  await expect(page.getByRole('table', { name: 'Historial de movimientos filtrados' }).getByRole('row').filter({ hasText: 'Compra feria' })).toHaveCount(1)
  await page.getByRole('button', { name: 'Acciones de Compra feria' }).click()
  await expect(page.getByRole('button', { name: 'Eliminar', exact: true })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Mis cuentas', exact: true }).click()
  await expect(overview(page, 'Cuenta corriente')).toContainText('$1.660.600')
  await page.getByRole('button', { name: 'Presupuestos', exact: true }).click()
  await expect(overview(page, 'Alimentación')).toContainText('$379.400')
  await page.getByRole('button', { name: 'Dashboard', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Saldos del dashboard' })).toContainText('$2.730.600')
  await expect(page.getByRole('region', { name: 'Próximos cobros y pagos' })).not.toContainText('Compra feria')
  await page.getByRole('button', { name: /^Notificaciones/ }).click()
  await expect(page.getByRole('dialog', { name: 'Bandeja de notificaciones' })).toContainText('Compra feria')
})

test('valida la fecha efectiva de un cobro y excluye un pago reprogramado y cancelado', async ({ page }) => {
  await page.goto('/#compromisos')
  await create(page, { name: 'Cobro del taller', amount: '50000', date: '2026-11-24', receipt: true })
  await expect(row(page, 'Cobro del taller')).not.toContainText('Vencido')
  await row(page, 'Cobro del taller').getByRole('button', { name: 'Cobro del taller', exact: true }).click()
  await page.getByRole('button', { name: 'Confirmar cobro' }).click()
  const confirm = page.getByRole('dialog', { name: 'Confirmar cobro' })
  await confirm.getByLabel('Fecha efectiva de recepción').fill('2026-11-25')
  await confirm.getByRole('button', { name: 'Confirmar cobro' }).click()
  await expect(confirm).toContainText('La fecha efectiva debe ser hoy o anterior.')
  await confirm.getByLabel('Fecha efectiva de recepción').fill('2026-11-22')
  await confirm.getByRole('button', { name: 'Confirmar cobro' }).click()
  await expect(page.getByText('Cobro confirmado.', { exact: true })).toBeVisible()
  await expect(overview(page, 'Saldo actual')).toContainText('$2.535.600')

  await create(page, { name: 'Equipo pospuesto', amount: '5000000', date: '2026-11-23' })
  await expect(overview(page, 'Saldo actual')).toContainText('$2.535.600')
  await expect(page.getByRole('complementary', { name: 'Análisis preventivo' })).toContainText('Posible déficit')
  await row(page, 'Equipo pospuesto').getByRole('button', { name: 'Equipo pospuesto', exact: true }).click()
  const detail = page.getByRole('dialog', { name: 'Equipo pospuesto' })
  await detail.getByRole('button', { name: 'Editar compromiso' }).click()
  const edit = page.getByRole('dialog', { name: 'Editar compromiso' })
  await edit.getByLabel('Fecha de vencimiento').fill('2026-12-10')
  await edit.getByRole('button', { name: 'Guardar cambios' }).click()
  await row(page, 'Equipo pospuesto').getByRole('button', { name: 'Equipo pospuesto', exact: true }).click()
  await expect(detail).toContainText('Vencimiento original')
  await expect(detail).toContainText('23 de noviembre')
  await detail.getByRole('button', { name: 'Cancelar compromiso' }).click()
  await page.getByRole('dialog', { name: 'Cancelar compromiso' }).getByRole('button', { name: 'Cancelar compromiso' }).click()
  await expect(page.getByText('Compromiso cancelado.', { exact: true })).toBeVisible()
  await expect(overview(page, 'Saldo proyectado')).toContainText('$2.845.600')
  await history(page).getByLabel('Estado del compromiso').selectOption('cancelado')
  await expect(row(page, 'Equipo pospuesto')).toContainText('Cancelado')
  await expect(row(page, 'Cobro del taller')).toHaveCount(0)
  await page.getByRole('button', { name: 'Presupuestos', exact: true }).click()
  await expect(overview(page, 'Alimentación')).toContainText('$314.400')
})

test('muestra el déficit transitorio del escenario y permite seleccionar días, excluir cobros y restablecer', async ({ page }) => {
  await page.goto('/#compromisos')
  await page.getByRole('button', { name: '7 días', exact: true }).click()
  await expect(overview(page, 'Saldo proyectado')).toContainText('$3.075.610')
  await page.getByRole('button', { name: '30 días', exact: true }).click()
  await page.getByRole('button', { name: 'Abrir simulador' }).click()
  const simulator = page.getByRole('region', { name: 'Modo simulación' })
  await simulator.getByLabel('Nombre hipotético').fill('Pago excepcional')
  await simulator.getByLabel('Fecha simulada').fill('2026-11-25')
  await simulator.getByLabel('Monto simulado (CLP)').fill('2600000')
  await simulator.getByRole('button', { name: 'Agregar al escenario' }).click()
  const comparison = simulator.getByRole('table')
  await expect(comparison.getByRole('row', { name: /Saldo final/ })).toContainText('$195.600')
  await expect(comparison.getByRole('row', { name: /Primer déficit/ })).toContainText('25 de noviembre')
  await expect(simulator).toContainText('25 nov a 30 nov')
  await expect(overview(page, 'Saldo proyectado')).toContainText('$2.795.600')
  const graph = page.getByRole('region', { name: 'Flujo de caja proyectado' })
  await graph.getByRole('button', { name: /Consultar flujo del 25 de noviembre/ }).click()
  await expect(graph.getByLabel('Fecha del flujo de caja')).toHaveValue('2026-11-25')
  await graph.getByLabel('Fecha del flujo de caja').selectOption('2026-11-24')
  await graph.getByLabel('Fecha del flujo de caja').selectOption('2026-11-25')
  await expect(graph).toContainText('Pago excepcional')
  await expect(graph).toContainText('Hipotético')
  await simulator.getByLabel('Compromiso a simular').selectOption('freelance')
  await simulator.getByLabel('Excluir este cobro del escenario').check()
  await simulator.getByRole('button', { name: 'Aplicar al escenario' }).click()
  await expect(comparison.getByRole('row', { name: /Saldo final/ })).toContainText('$-424.400')
  await simulator.getByLabel('Reserva simulada (CLP)').fill('3000000')
  await simulator.getByRole('button', { name: 'Aplicar reserva' }).click()
  await expect(page.getByRole('complementary', { name: 'Análisis preventivo' })).toContainText('Saldo inferior a la reserva')
  await simulator.getByRole('button', { name: 'Restablecer escenario' }).click()
  await expect(comparison.getByRole('row', { name: /Saldo final/ }).getByRole('cell').last()).toHaveText('$2.795.600')
  await simulator.getByLabel('Tipo hipotético').selectOption('cobro')
  await simulator.getByLabel('Nombre hipotético').fill('Cobro adicional')
  await simulator.getByLabel('Monto simulado (CLP)').fill('30000')
  await simulator.getByRole('button', { name: 'Agregar al escenario' }).click()
  await expect(comparison.getByRole('row', { name: /Saldo final/ }).getByRole('cell').last()).toHaveText('$2.825.600')
  await simulator.getByRole('button', { name: 'Cerrar simulador' }).click()
  await expect(history(page)).not.toContainText('Pago excepcional')
  await expect(history(page)).not.toContainText('Cobro adicional')
})

test('usa un calendario bisiesto y un drawer móvil con privacidad compartida', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 820 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Abrir menú' }).click()
  await page.getByRole('button', { name: 'Cobros y pagos', exact: true }).click()
  await expect(overview(page, 'Saldo actual')).toContainText('$2.485.600')
  await page.getByRole('button', { name: 'Ocultar montos' }).click()
  await expect(overview(page, 'Saldo actual')).toContainText('$••••••')
  await expect(page.getByRole('region', { name: 'Flujo de caja proyectado' })).not.toContainText('$2.485.600')
  await page.getByRole('button', { name: 'Calendario', exact: true }).click()
  const calendar = page.getByRole('region', { name: 'Calendario financiero' })
  await calendar.getByRole('button', { name: /29 de noviembre.*Pagos previstos/ }).click()
  await expect(calendar.getByRole('list', { name: 'Compromisos del día' })).toContainText('Internet hogar')
  await calendar.getByLabel('Año de calendario').fill('2028')
  await calendar.getByLabel('Año de calendario').press('Tab')
  await calendar.getByLabel('Mes de calendario').selectOption('02')
  await calendar.getByRole('button', { name: '29 de febrero de 2028', exact: true }).click()
  await calendar.getByRole('button', { name: 'Agregar compromiso' }).click()
  const form = page.getByRole('dialog', { name: 'Nuevo compromiso' })
  await expect(form.getByLabel('Fecha de vencimiento')).toHaveValue('2028-02-29')
  expect(await form.evaluate(node => Math.round(node.getBoundingClientRect().bottom))).toBe(820)
  await form.getByRole('button', { name: 'Cerrar', exact: true }).click()
  await calendar.getByRole('button', { name: 'Mes actual' }).click()
  await expect(calendar.getByRole('button', { name: /24 de noviembre/ })).toHaveAttribute('aria-current', 'date')
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
})
