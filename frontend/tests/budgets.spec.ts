import { expect, test, type Page } from '@playwright/test'

const card = (page: Page, name: string) => page.getByRole('article', { name, exact: true })
const summary = (page: Page) => page.getByRole('region', { name: 'Resumen presupuestario' })
const history = (page: Page) => page.getByRole('table', { name: 'Historial de movimientos filtrados' })

async function action(page: Page, category: string, label: string) {
  await card(page, category).getByRole('button', { name: `Acciones de ${category}` }).click()
  await page.getByRole('dialog', { name: 'Acciones del presupuesto' }).getByRole('button', { name: label, exact: true }).click()
}

test.beforeEach(async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-11-24T12:00:00Z'))
})

test('crea desde gastos sin presupuesto, valida duplicados, edita y elimina sin mover saldos', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Presupuestos', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Presupuestos', exact: true })).toHaveAttribute('aria-current', 'page')
  for (const total of ['$840.000', '$710.400', '$129.600']) await expect(summary(page)).toContainText(total)
  const cards = page.getByRole('region', { name: 'Presupuestos por categoría' }).getByRole('article')
  await expect(cards).toHaveCount(4)
  expect(await cards.evaluateAll(items => new Set(items.map(item => Math.round(item.getBoundingClientRect().top))).size)).toBe(1)
  await expect(page.getByRole('region', { name: 'Ritmo presupuestario del mes' })).toContainText('$524.000')
  await expect(card(page, 'Alimentación')).toContainText('Podrías superar este presupuesto')
  await expect(card(page, 'Alimentación')).toContainText('Cerca del límite')

  await page.getByRole('button', { name: 'Crear presupuesto de Vivienda' }).click()
  let editor = page.getByRole('dialog', { name: 'Nuevo presupuesto' })
  await expect(editor.getByLabel('Categoría de gasto')).toHaveValue('vivienda')
  await editor.getByLabel('Límite mensual (CLP)').fill('420000.5')
  await editor.getByLabel('Umbral de advertencia (%)').fill('101')
  await editor.getByRole('button', { name: 'Crear presupuesto' }).click()
  await expect(editor.getByLabel('Límite mensual (CLP)')).toHaveAttribute('aria-invalid', 'true')
  await expect(editor.getByLabel('Umbral de advertencia (%)')).toHaveAttribute('aria-invalid', 'true')
  await editor.getByLabel('Límite mensual (CLP)').fill('420000')
  await editor.getByLabel('Umbral de advertencia (%)').fill('65')
  await editor.getByLabel(/Descripción/).fill('Plan de vivienda')
  await editor.getByRole('button', { name: 'Crear presupuesto' }).click()
  await expect(card(page, 'Vivienda')).toContainText('Límite alcanzado')
  await expect(summary(page)).toContainText('$1.130.400')
  await expect(page.getByRole('region', { name: 'Alertas del período' })).toContainText('Alcanzaste el límite mensual.')

  await page.getByRole('button', { name: 'Nuevo presupuesto', exact: true }).click()
  await editor.getByLabel('Categoría de gasto').selectOption('vivienda')
  await editor.getByLabel('Límite mensual (CLP)').fill('500000')
  await editor.getByRole('button', { name: 'Crear presupuesto' }).click()
  await expect(editor).toContainText('Ya existe un presupuesto para esta categoría y período.')
  await editor.getByRole('button', { name: 'Cancelar' }).click()

  await action(page, 'Vivienda', 'Editar presupuesto')
  editor = page.getByRole('dialog', { name: 'Editar presupuesto' })
  await expect(editor.getByLabel('Categoría de gasto')).toBeDisabled()
  await expect(editor.getByLabel('Mes', { exact: true })).toBeDisabled()
  await editor.getByLabel('Límite mensual (CLP)').fill('480000')
  await editor.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(card(page, 'Vivienda')).toContainText('Cerca del límite')
  await expect(page.getByRole('region', { name: 'Alertas del período' })).toContainText('Alcanzaste tu umbral de advertencia del 65 %.')

  await page.getByRole('button', { name: 'Dashboard', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Presupuestos del mes' })).toContainText('$480.000')
  await expect(page.getByRole('region', { name: 'Saldos del dashboard' })).toContainText('$2.485.600')
  await page.getByRole('link', { name: 'Ver presupuestos' }).click()
  await action(page, 'Vivienda', 'Eliminar presupuesto')
  await page.getByRole('dialog', { name: 'Eliminar presupuesto' }).getByRole('button', { name: 'Eliminar presupuesto' }).click()
  await expect(card(page, 'Vivienda')).toHaveCount(0)
  await expect(summary(page)).toContainText('$710.400')
  await expect(page.getByRole('region', { name: 'Gastos sin presupuesto' })).toContainText('$420.000')
})

test('deriva el consumo del gasto compartido y revierte reclasificaciones y eliminaciones', async ({ page }) => {
  await page.goto('/#presupuestos')
  await page.getByRole('button', { name: 'Registrar movimiento' }).click()
  let editor = page.getByRole('dialog', { name: 'Registrar movimiento' })
  await editor.getByLabel('Monto (CLP)').fill('15000')
  await editor.getByLabel('Categoría').selectOption('alimentacion')
  await editor.getByLabel(/Descripción/).fill('Gasto compartido')
  await editor.getByRole('button', { name: 'Guardar movimiento' }).click()
  await expect(card(page, 'Alimentación')).toContainText('$329.400')

  await card(page, 'Alimentación').getByRole('button', { name: 'Alimentación', exact: true }).click()
  const detail = page.getByRole('dialog', { name: 'Alimentación' })
  await expect(detail.getByRole('region', { name: 'Consumo acumulado' })).toContainText('24 de 30 días')
  await detail.getByRole('button', { name: 'Ver gastos del presupuesto' }).click()
  await expect(page.getByRole('button', { name: 'Quitar filtro Alimentación' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Quitar filtro Gasto', exact: true })).toBeVisible()
  await expect(history(page)).toContainText('Gasto compartido')
  await page.getByRole('button', { name: 'Acciones de Gasto compartido' }).click()
  await page.getByRole('button', { name: 'Editar', exact: true }).click()
  editor = page.getByRole('dialog', { name: 'Editar movimiento' })
  await editor.getByLabel('Categoría').selectOption('transporte')
  await editor.getByRole('button', { name: 'Guardar movimiento' }).click()
  await expect(page.getByText('Movimiento actualizado.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Presupuestos', exact: true }).click()
  await expect(card(page, 'Alimentación')).toContainText('$314.400')
  await expect(card(page, 'Transporte')).toContainText('$162.000')

  await page.getByRole('button', { name: 'Registrar movimiento' }).click()
  editor = page.getByRole('dialog', { name: 'Registrar movimiento' })
  await editor.getByRole('button', { name: 'Transferencia', exact: true }).click()
  await editor.getByLabel('Cuenta de destino').selectOption('vista')
  await editor.getByLabel('Monto (CLP)').fill('10000')
  await editor.getByRole('button', { name: 'Guardar movimiento' }).click()
  await expect(editor).toBeHidden()
  await expect(summary(page)).toContainText('$725.400')

  await page.getByRole('button', { name: 'Movimientos', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Buscar por descripción' }).fill('Gasto compartido')
  await page.getByRole('button', { name: 'Acciones de Gasto compartido' }).click()
  await page.getByRole('button', { name: 'Eliminar', exact: true }).click()
  await page.getByRole('dialog', { name: 'Eliminar movimiento' }).getByRole('button', { name: 'Eliminar movimiento' }).click()
  await expect(page.getByText('Movimiento eliminado.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Presupuestos', exact: true }).click()
  await expect(card(page, 'Transporte')).toContainText('$147.000')
  await expect(summary(page)).toContainText('$710.400')
})

test('copia una categoría o toda la planificación sin sobrescribir ni trasladar gastos', async ({ page }) => {
  await page.goto('/#presupuestos')
  await action(page, 'Alimentación', 'Duplicar presupuesto')
  let dialog = page.getByRole('dialog', { name: 'Duplicar presupuesto' })
  await expect(dialog.getByLabel('Mes', { exact: true })).toHaveValue('12')
  await dialog.getByRole('button', { name: 'Copiar presupuesto' }).click()
  await expect(card(page, 'Alimentación')).toContainText('$360.000')
  await expect(card(page, 'Alimentación')).toContainText('El mes aún no comienza')
  await expect(summary(page).getByRole('article').filter({ hasText: 'Total consumido' })).toContainText('$0')
  await page.getByRole('button', { name: 'Este mes', exact: true }).click()
  await page.getByRole('button', { name: 'Duplicar planificación' }).click()
  dialog = page.getByRole('dialog', { name: 'Duplicar planificación' })
  await expect(dialog.getByRole('alert')).toContainText('Alimentación')
  await expect(dialog.getByRole('button', { name: 'Copiar planificación' })).toBeDisabled()
  await dialog.getByLabel('Mes', { exact: true }).selectOption('01')
  await dialog.getByLabel('Año', { exact: true }).fill('2027')
  await dialog.getByRole('button', { name: 'Copiar planificación' }).click()
  await expect(page.getByRole('region', { name: 'Presupuestos por categoría' }).getByRole('article')).toHaveCount(4)
  await expect(summary(page)).toContainText('$840.000')
  await page.getByRole('button', { name: 'Este mes', exact: true }).click()
  await page.getByRole('button', { name: 'Mes anterior', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Ritmo presupuestario del mes' })).toContainText('Mes cerrado')
  await card(page, 'Alimentación').getByRole('button', { name: 'Alimentación', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Alimentación' })).toContainText('Gasto al cierre')
  await expect(page.getByRole('dialog', { name: 'Alimentación' })).not.toContainText('Proyección lineal')
})

test.describe('presupuestos en móvil', () => {
  test.use({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })

  test('mantiene privacidad y permite abrir el detalle y los filtros del historial', async ({ page }) => {
    await page.goto('/')
    await page.getByRole('button', { name: 'Abrir menú' }).click()
    await page.getByRole('button', { name: 'Presupuestos', exact: true }).click()
    await expect(summary(page)).toContainText('$840.000')
    await page.getByRole('button', { name: 'Registrar movimiento', exact: true }).click()
    await page.getByRole('dialog', { name: 'Registrar movimiento' }).getByRole('button', { name: 'Cancelar' }).click()
    await page.getByRole('button', { name: 'Ocultar montos' }).click()
    await expect(summary(page)).toContainText('$••••••')
    await expect(page.getByRole('region', { name: 'Distribución presupuestaria' })).not.toContainText('$840.000')
    await page.setViewportSize({ width: 320, height: 740 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
    await card(page, 'Alimentación').getByRole('button', { name: 'Alimentación', exact: true }).click()
    const detail = page.getByRole('dialog', { name: 'Alimentación' })
    await expect(detail).toContainText('$••••••')
    await detail.getByRole('button', { name: 'Ver gastos del presupuesto' }).click()
    await expect(page.getByRole('button', { name: 'Quitar filtro Alimentación' })).toBeVisible()
    await expect(page.getByRole('list', { name: 'Movimientos del historial' })).toContainText('$••••••')
  })
})
